"""Graph spine: Home -> subject maps -> everything else, as real links (so the Obsidian graph is a tree with chords).

    .venv/bin/python -W ignore scripts/graph_spine.py            # report only
    .venv/bin/python -W ignore scripts/graph_spine.py --apply    # (re)write the atlas block at the end of every subject map

Why: the graph view draws only real `[[links]]` (Dataview lists are invisible to it).  Home linked the maps already, but a
subject's notes were reachable from its map only through whatever chapters happened to mention them, and the other tool's
source notes hung off nothing, so the force layout had no single centre.  The atlas block lists EVERY note of the subject
(chapters, concept notes, other vault notes, and the other tool's source notes assigned to the subject by
`graph_colors.py`), inside a collapsed callout so the maps stay readable.  The block lives between the two marker comments
and is regenerated; everything outside the markers is untouched (add-only rule).  Stray source notes (maps/, inbox/,
loose zettel) are listed in an atlas at the end of Home.

Home also carries an "All chapters" index (second generated block): Home -> every chapter of every subject.  In the calibrated
layout simulation (scripts/graph_sim.py, scripts/_work/design.py) this evens out the angular spacing of the subject lobes around
Home and makes Home the best-connected node, i.e. the visual centre.  A rim of map-to-map links was also tried and does nothing
(d3's link strength 1/min(degree) is tiny between two hubs), so it is not used.
"""
import argparse
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import graph_colors as gc  # noqa: E402

START = "<!-- graph-spine:start (generated by scripts/graph_spine.py; do not edit between the markers) -->"
END = "<!-- graph-spine:end -->"
CH_START = "<!-- graph-spine-chapters:start (generated by scripts/graph_spine.py; do not edit between the markers) -->"
CH_END = "<!-- graph-spine-chapters:end -->"
HOME = "00-Home/Home.md"

# subject key (graph_colors group key) -> its map note
MAPS = {
    "climate": "01-Climate/Climate - Course Map.md",
    "eco-evo": "02-Eco-Evo/Ecology and Evolution - Course Map.md",
    "thermo": "03-Thermodynamics-and-Statistical-Mechanics/Thermodynamics and Statistical Mechanics - Course Map.md",
    "earth-evo": "04-Evolution-of-Earth-and-Life/Evolution of Earth and Life - Course Map.md",
    "landscapes": "05-Landscapes-Geomorphology/Landscapes and Geomorphology - Course Map.md",
    "qm": "06-Quantum-Mechanics/Quantum Mechanics - Course Map.md",
    "waves": "07-Waves/Waves - Course Map.md",
    "probability": "08-Probability/Probability - Course Map.md",
    "foundations": "09-Foundations/09-Foundations.md",
    "group": "10-Group-Theory/Group Theory - Course Map.md",
    "analysis": "11-Proofs-Analysis-Topology/Proofs, Analysis and Topology - Course Map.md",
    "chem": "12-Inorganic-Chemistry/Inorganic Chemistry - Course Map.md",
    "neuro": "13-Neuroscience/Neuroscience - Course Map.md",
}
# source-layer group key -> subject key
SRC_TO_SUBJECT = {"src-qm": "qm", "src-chem": "chem", "src-group": "group", "src-analysis": "analysis",
                  "src-probability": "probability", "src-climate": "climate", "src-landscapes": "landscapes"}
FOLDER_TO_SUBJECT = {os.path.dirname(m).split("/")[0]: k for k, m in MAPS.items()}


def subject_of(rel, group_key):
    top = rel.split("/")[0]
    if top in FOLDER_TO_SUBJECT:
        return FOLDER_TO_SUBJECT[top]
    if group_key in SRC_TO_SUBJECT:
        return SRC_TO_SUBJECT[group_key]
    if group_key in MAPS:
        return group_key
    return None


def link_name(rel, basenames):
    """Shortest unambiguous wiki-link for a note path."""
    name = os.path.basename(rel)[:-3]
    if basenames[name.lower()] == 1:
        return f"[[{name}]]"
    return f"[[{rel[:-3]}|{name}]]"


def classify(rel, tags):
    t = set(tags)
    if "type/chapter" in t:
        return "chapters"
    if "type/concept" in t or "/Concepts/" in rel:
        return "concepts"
    return "other"


def build():
    gc.SEARCH = gc.SEARCH_BASE            # the atlas lists the source notes too, even though the default graph filter hides them
    notes = gc.load_notes()
    asg = gc.assign(notes)
    basenames = collections.Counter(os.path.basename(r)[:-3].lower() for r in notes)
    by_subject = collections.defaultdict(lambda: collections.defaultdict(list))
    stray = []
    for rel, (grp, _) in asg.items():
        if rel == HOME or rel in MAPS.values():
            continue
        key = grp[0] if grp else None
        sub = subject_of(rel, key)
        if sub is None:
            stray.append(rel)
            continue
        is_src = rel.split("/")[0] not in FOLDER_TO_SUBJECT
        kind = "source" if is_src else classify(rel, notes[rel]["tags"])
        by_subject[sub][kind].append(rel)
    return notes, basenames, by_subject, stray


def block(title, groups, basenames, intro):
    total = sum(len(v) for v in groups.values())
    parts = []
    labels = [("chapters", "Chapters"), ("concepts", "Concept notes"), ("other", "Other notes in the vault"),
              ("source", "Notes from the other tool (source layer)")]
    summary = " · ".join(f"{len(groups[k])} {lab.lower()}" for k, lab in labels if groups.get(k))
    for k, lab in labels:
        items = sorted(groups.get(k, []), key=lambda r: os.path.basename(r).lower())
        if items:
            parts.append(f"> **{lab} ({len(items)}):** " + " · ".join(link_name(r, basenames) for r in items))
            parts.append(">")
    body = "\n".join(parts).rstrip(">\n")
    if not total:
        return (f"{START}\n## {title}\n{intro}\n\n> [!abstract]- Atlas (generated): no notes yet (stub subject)\n"
                f"> Nothing to list yet; this block fills itself when `scripts/graph_spine.py --apply` is re-run after the first notes are written.\n{END}\n", 0)
    return (f"{START}\n## {title}\n{intro}\n\n> [!abstract]- Atlas (generated): {summary}\n{body}\n{END}\n", total)


def write_block(path, text, start=None, end=None):
    start, end = start or START, end or END
    t = open(path, encoding="utf-8").read()
    if start in t:
        t = re.sub(re.escape(start) + r".*?" + re.escape(end) + r"\n?", lambda m: text, t, flags=re.S)
    else:
        t = t.rstrip("\n") + "\n\n" + text
    open(path, "w", encoding="utf-8").write(t)


MAP_LABEL = {"climate": "Climate", "eco-evo": "Ecology and Evolution", "thermo": "Thermodynamics", "earth-evo": "Evolution of Earth and Life",
             "landscapes": "Landscapes", "qm": "Quantum Mechanics", "waves": "Waves", "probability": "Probability", "foundations": "Foundations",
             "group": "Group Theory", "analysis": "Proofs, Analysis and Topology", "chem": "Inorganic Chemistry", "neuro": "Neuroscience"}


def chapters_block(by_subject, basenames):
    lines = [CH_START, "## All chapters (generated index: Home links every chapter)",
             "The centre of the vault graph: **Home** links every subject map (the hubs) and every chapter below, so the graph radiates from here. "
             "Regenerate with `scripts/graph_spine.py --apply` after adding a chapter.", ""]
    n = 0
    for sub, m in MAPS.items():
        chs = sorted(by_subject[sub]["chapters"], key=lambda r: os.path.basename(r).lower())
        mp = m[:-3]
        head = f"[[{mp}|{MAP_LABEL[sub]}]]"
        if chs:
            lines.append(f"- **{head}** ({len(chs)}): " + " · ".join(link_name(r, basenames) for r in chs))
            n += len(chs)
        else:
            lines.append(f"- **{head}**: no chapters yet")
    lines += ["", CH_END, ""]
    return "\n".join(lines), n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    notes, basenames, by_subject, stray = build()
    print(f"{'subject':12s} {'chapters':>8} {'concepts':>8} {'other':>6} {'source':>7}")
    for sub, m in MAPS.items():
        g = by_subject[sub]
        print(f"{sub:12s} {len(g['chapters']):8d} {len(g['concepts']):8d} {len(g['other']):6d} {len(g['source']):7d}")
        text, _ = block("Atlas: every note in this subject", g, basenames,
                        "The graph view draws only real links, so this block links **every** note of the subject "
                        "(the map is the hub of its cluster; [[Home]] is the hub of all maps).")
        if a.apply:
            write_block(os.path.join(gc.ROOT, m), text)
    print("stray source notes (attached to Home):", len(stray))
    if a.apply:
        text, _ = block("Atlas: the other tool's loose notes", {"source": stray}, basenames,
                        "Source notes that belong to no single subject (the other tool's `maps/`, `inbox/` and uncategorised zettel).")
        write_block(os.path.join(gc.ROOT, HOME), text)
        text, n = chapters_block(by_subject, basenames)
        write_block(os.path.join(gc.ROOT, HOME), text, CH_START, CH_END)
        print(f"atlas blocks written; Home chapter index lists {n} chapters")


if __name__ == "__main__":
    main()
