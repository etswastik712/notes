def ls27():
    head("LS27  Coasts: beaches, deltas and rocky shores")
    # ---- longshore energy flux and CERC
    def littoral(Hb, ab_deg, K=0.39, gam=0.78, p=0.4):
        P = RHO_SEA * G / 8 * Hb ** 2 * math.sqrt(G * Hb / gam) * math.sin(math.radians(ab_deg)) * math.cos(math.radians(ab_deg))
        Q = K * P / ((RHO_S - RHO_SEA) * G * (1 - p))
        return P, Q
    print("longshore energy flux P_l = (E C_g)_b sin a cos a with C_g = sqrt(g h_b), h_b = H_b/0.78; volume rate Q = K P_l / ((rho_s - rho) g (1-p)), K = 0.39:")
    for Hb, ab in ((0.5, 5), (1.0, 5), (1.0, 10), (2.0, 10), (2.0, 30), (2.0, 45), (2.0, 60)):
        P, Q = littoral(Hb, ab)
        print(f"   H_b = {Hb} m, alpha_b = {ab:2d} deg: P_l = {P:7.0f} W/m, Q = {Q:.4f} m3/s = {Q*YR/1e6:7.3f} million m3/yr")
    P1, Q1 = littoral(1.0, 10); P2, Q2 = littoral(2.0, 10)
    ok("Q ~ H_b^(5/2)", abs(Q2 / Q1 - 2 ** 2.5) < 1e-9)
    ang = np.linspace(1, 89, 8801)
    qa = np.array([littoral(1.0, a)[1] for a in ang])
    print(f"   Q ~ sin(2 alpha): maximum at alpha = {ang[np.argmax(qa)]:.1f} deg (45)")
    ok("maximum drift at 45 degrees", abs(ang[np.argmax(qa)] - 45) < 0.1)
    P, Q = littoral(1.0, 10)
    print(f"   coefficient: P_l = 0.0707 rho g^(3/2) H_b^(5/2) sin 2a... check: {0.5/(8*math.sqrt(0.78))*RHO_SEA*G**1.5*1.0*math.sin(math.radians(20)):.1f} W/m vs {P:.1f}")
    ok("closed form for P_l", abs(0.5 / (8 * math.sqrt(0.78)) * RHO_SEA * G ** 1.5 * math.sin(math.radians(20)) - P) / P < 1e-9)
    # net versus gross drift
    classes = [(0.6, 1.2, +10), (0.3, 0.8, -15), (0.1, 2.5, -8)]       # (fraction of time, H_b, angle; sign = direction)
    net = gross = 0.0
    for f, Hb, a in classes:
        _, Q = littoral(Hb, abs(a))
        net += f * Q * math.copysign(1, a)
        gross += f * Q
    print(f"   wave climate: 60% H 1.2 m from +10 deg, 30% 0.8 m from -15 deg, 10% 2.5 m from -8 deg: gross = {gross*YR/1e6:.3f} Mm3/yr, net = {net*YR/1e6:.3f} Mm3/yr ({net/gross*100:+.0f}% of gross): the rare big waves (10%) carry {0.1*littoral(2.5,8)[1]/gross*100:.0f}% of the gross drift")
    # ---- coastline instability
    print("\nshoreline evolution: D dy/dt = -dQ/dx, Q = Q0 sin 2(a0 - dy/dx)  ->  dy/dt = (2 Q0 cos 2 a0 / D) d2y/dx2  (small angles)")
    Q0, Dc = 1.0e6, 10.0
    for a0 in (15, 30, 44, 46, 60, 75):
        kap = 2 * Q0 * math.cos(2 * math.radians(a0)) / Dc
        print(f"   waves at {a0:2d} deg: diffusivity kappa = {kap:12.0f} m2/yr {'(smoothing)' if kap>0 else '(anti-diffusion: growth)'}")
    for lam in (1e3, 1e4, 1e5):
        k = 2 * math.pi / lam
        kap = 2 * Q0 * math.cos(2 * math.radians(15)) / Dc
        print(f"      15 deg, perturbation of wavelength {lam/1e3:5.0f} km decays with time constant 1/(kappa k^2) = {1/(kap*k**2):10.2f} yr")
    # numerical check of the linearised result with the full nonlinear flux
