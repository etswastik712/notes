    print(f"mean potential energy per unit area of a sinusoidal surface (H = {Hw} m): {PE - PE0:.1f} J/m2 above still water; rho g H^2/16 = {RHO*G*Hw**2/16:.1f}; kinetic equals potential -> total rho g H^2/8")
