    print(f"   Snell's law: sin(alpha)/C constant: C0/Cb = {C0/Cb:.2f} so sin alpha_b = sin 30 deg / {C0/Cb:.2f}")
    # refraction over a canyon vs headland: energy flux conservation b0 Cg0 H0^2 = b Cg H^2
    print("   ray convergence: wave rays spaced b0 offshore and b at breaking: H/H0 = K_s sqrt(b0/b); a headland that focuses rays 2:1 raises H by x" + f"{math.sqrt(2):.2f} and the power by x2")
    # ---- storm surge
    dP = 101300 - 90000
