def strahler_counts(n_leaves, rng):
    """Random-topology (Shreve) network with n_leaves sources, generated by the cycle lemma; returns {Strahler order: number of streams}."""
    n_int = n_leaves - 1
    seq = np.array([1] * n_int + [-1] * n_leaves)           # +1 branching node, -1 source; preorder of a plane binary tree
    rng.shuffle(seq)
    k = int(np.argmin(np.cumsum(seq)))
    seq = np.concatenate([seq[k + 1:], seq[:k + 1]])
    left, right, kind, par = {}, {}, {}, {}
    st = []
    for i, s in enumerate(seq):
        kind[i] = s
        if st:
            p = st[-1]
            par[i] = p
            if p in left:
                right[p] = i
            else:
                left[p] = i
            while st and st[-1] in right:
                st.pop()
        if s == 1:
            st.append(i)
    # a node whose both children are set is complete; the loop above pops completed parents only after a child is attached
    order = {}
    stk = [(0, 0)]
    while stk:
        nd, state = stk.pop()
        if kind[nd] == -1:
            order[nd] = 1
        elif state == 0:
            stk.append((nd, 1)); stk.append((right[nd], 0)); stk.append((left[nd], 0))
        else:
            a, b = order[left[nd]], order[right[nd]]
            order[nd] = a + 1 if a == b else max(a, b)
    cnt = {}
    for nd, o in order.items():
        if nd == 0 or order[par[nd]] > o:
            cnt[o] = cnt.get(o, 0) + 1
    return cnt


