    print(f"Rayleigh sea, H_s = {Hs} m: simulated H_rms = {Hrms:.3f} m (theory sqrt(2) sigma = {math.sqrt(2)*sig:.3f}), mean of the highest third = {h13:.3f} m (theory 2 sigma = {2*sig:.3f}) = {h13/Hrms:.3f} H_rms (1.416)")
    ok("H_1/3 = 1.416 H_rms = 2 sigma for a Rayleigh sea", abs(h13 / Hs - 1) < 0.01 and abs(h13 / Hrms - 1.416) < 0.01)
