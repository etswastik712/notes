    ok("expected maximum of 3000 waves ~ sigma sqrt(2 ln N)", abs(Hmax / (sig * math.sqrt(2 * math.log(3000))) - 1) < 0.06)
    P_by_class = np.sort(Hr) ** 2
    top = P_by_class[-len(Hr) // 10:].sum() / P_by_class.sum()
    print(f"   the largest 10% of waves carry {top*100:.1f}% of the wave energy (H^2 is exponentially distributed: 0.1 (1 + ln 10) = {0.1*(1+math.log(10))*100:.1f}%)")
    ok("energy share of the top 10% = q (1 + ln 1/q)", abs(top - 0.1 * (1 + math.log(10))) < 0.01)


