def wave_k(T, h):
    w = 2 * math.pi / T
    k = w ** 2 / G
    for _ in range(100):
        k = w ** 2 / (G * math.tanh(k * h))
    return k


def wave_props(T, h):
    k = wave_k(T, h)
    w = 2 * math.pi / T
    C = w / k
    n = 0.5 * (1 + 2 * k * h / math.sinh(2 * k * h))
    return k, C, n * C, n


