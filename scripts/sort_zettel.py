"""Sort the other tool's zettel notes into their subject vault and link them to chapters and concept notes.

    .venv/bin/python -W ignore scripts/sort_zettel.py            # plan only: where every note goes, what it links to
    .venv/bin/python -W ignore scripts/sort_zettel.py --apply    # move, tag and link (idempotent: safe to re-run)

What it does (user request 2026-10-30: "sort the notes in zettel to Concepts/zettel of the respective vaults and link them
properly to the respective chapters and concepts"):

  1. Every note in `zettel/` carries its source course as a tag (`introduction-to-probability`, `ph2113`, ...).  The course
     decides the vault (`COURSES`).  The note moves to `<vault>/Concepts/zettel/<slug>.md`.  The file name and the `id:` line
     stay as they were: Obsidian resolves a path link by suffix, so every existing `[[zettel/<slug>]]` link keeps working
     with no rewriting (scripts/link_audit.py uses the same rule).
  2. The tag `subject/<x>` is added to the note's tags, so the colour groups and tag queries of the vault see it.
  3. Each note gets a generated block `vault:links` (after the other tool's own `kurooto:seen` block, which is untouched):
     `chapter::` (the chapter it belongs to), `concept::` (the vault's concept note on the same idea) and `related-concept::`.
     A note that no chapter covers links to the course map instead (`map::`).
  4. Each chapter gets a generated `## Zettel notes` block (before `## Provenance`) and each concept note one (before
     `## Linked from`), so the links run both ways.

Matching = TF-IDF cosine between the note and each chapter, + a bonus when the note's title occurs in the chapter text, + a
bonus from the concept note it matches (chapters named in its "Used in:" line, chapters that link to it).  `OVERRIDES` pins
what the reviewer decided by hand; `FOUNDATION` etc. need no entry.  Add-only: nothing is deleted from any note.

The other tool (Kurooto) only scans `zettel/` for its concept notes (core/conceptgraph.py: concept_dirs), so after this move it
no longer sees the moved notes.  New notes keep arriving in `zettel/`: run this script again afterwards.  A slug that exists
both in `zettel/` and in a vault is reported as a duplicate and left alone.
"""
import argparse
import collections
import json
import math
import os
import re
import shutil

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ZDIR = os.path.join(ROOT, "zettel")

# source course tag -> (vault folder, subject tag)
COURSES = {
    "introduction-to-climate-science": ("01-Climate", "climate"),
    "landscape-evolution": ("05-Landscapes-Geomorphology", "landscapes"),
    "ph2113": ("06-Quantum-Mechanics", "qm"),
    "introduction-to-probability": ("08-Probability", "probability"),
    "mt3184-differential-geometry-and-lie-groups": ("10-Group-Theory", "group-theory"),
    "intro-to-proofs": ("11-Proofs-Analysis-Topology", "analysis"),
    "ch2113-principles-of-inorganic-chemistry-august-20": ("12-Inorganic-Chemistry", "chemistry"),
}

SUB = "Concepts/zettel"
Z_START = "<!-- zettel:start (generated by scripts/sort_zettel.py; do not edit between the markers) -->"
Z_END = "<!-- zettel:end -->"
V_START = "<!-- vault:links start (generated by scripts/sort_zettel.py; do not edit between the markers) -->"
V_END = "<!-- vault:links end -->"

# Hand decisions after reviewing the plan: slug -> {"chapter": chapter file name without .md or None (course map only),
#                                                   "concepts": [...], "related": [...]}   (names of vault concept notes)
OVERRIDES = {}

STOP = set("""a an the of in on at to for from by with without and or nor but as is are was were be been being it its this that these
those into onto over under via per than then so such can may might will would should could not no any each every both either
their there where which who whom whose what when how why if else also only more most less least very upon within between among
about above below across after before during through while using use used based one two three four five six seven eight nine ten
given let form forms case cases note notes result results""".split())


# ---------------------------------------------------------------------------------------------------------------- text
def fm_split(text):
    m = re.match(r"---\n(.*?)\n---\n?", text, re.S)
    if not m:
        return {}, text
    try:
        fm = yaml.safe_load(m.group(1)) or {}
    except Exception:
        fm = {}
    return fm, text[m.end():]


def strip_generated(text):
    for a, b in ((Z_START, Z_END), (V_START, V_END)):
        text = re.sub(re.escape(a) + r".*?" + re.escape(b) + r"\n?", "", text, flags=re.S)
    text = re.sub(r"<!-- graph-spine.*?<!-- graph-spine[^>]*end -->", "", text, flags=re.S)
    return text


def plain(text):
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"<!--.*?-->", " ", text, flags=re.S)
    text = re.sub(r"\$\$.*?\$\$", " ", text, flags=re.S)
    text = re.sub(r"\$[^$\n]*\$", " ", text)
    text = re.sub(r"!\[\[[^\]]*\]\]", " ", text)
    text = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", text)
    text = re.sub(r"\[\[([^\]#]+)(#[^\]]*)?\]\]", lambda m: os.path.basename(m.group(1)), text)
    text = re.sub(r"https?://\S+", " ", text)
    return text


def stem(w):
    if len(w) > 4 and w.endswith("ies"):
        return w[:-3] + "y"
    if len(w) > 4 and w.endswith("sses"):
        return w[:-2]
    if len(w) > 3 and w.endswith("s") and not w.endswith(("ss", "us", "is")):
        w = w[:-1]
    for suf in ("ation", "ing", "ed", "ly"):
        if len(w) > len(suf) + 3 and w.endswith(suf):
            return w[: -len(suf)]
    return w


def tokens(text, keep_stop=False):
    out = []
    for w in re.findall(r"[a-z][a-z0-9]+(?:'[a-z]+)?", plain(text).lower().replace("’", "'")):
        w = re.sub(r"'s$", "", w)
        if not keep_stop and (w in STOP or len(w) < 3):
            continue
        out.append(stem(w))
    return out


def norm(name):
    return " ".join(tokens(name, keep_stop=True))


def tf_vector(parts):
    """parts: [(text, weight)] -> sublinear term-frequency dict."""
    c = collections.Counter()
    for text, wt in parts:
        for t in tokens(text):
            c[t] += wt
    return {t: 1 + math.log(v) if v >= 1 else v for t, v in c.items()}


def cosine(a, b, idf):
    num = sum(v * idf.get(t, 1.0) * b[t] * idf.get(t, 1.0) for t, v in a.items() if t in b)
    na = math.sqrt(sum((v * idf.get(t, 1.0)) ** 2 for t, v in a.items()))
    nb = math.sqrt(sum((v * idf.get(t, 1.0)) ** 2 for t, v in b.items()))
    return num / (na * nb) if na and nb else 0.0


def count_phrase(seq, phrase):
    n = len(phrase)
    return sum(1 for i in range(len(seq) - n + 1) if seq[i:i + n] == phrase) if n else 0


# --------------------------------------------------------------------------------------------------------------- loading
def load_zettel(path):
    text = open(path, encoding="utf-8").read()
    fm, body = fm_split(text)
    tags = [str(t) for t in (fm.get("tags") or [])]
    course = next((t for t in tags if t in COURSES), None)
    title = re.search(r"^# (.*)$", body, re.M)
    title = title.group(1).strip() if title else os.path.basename(path)[:-3]
    body = strip_generated(body)
    defn = re.split(r"\n## Links|\n---\n", body.split("\n", 2)[-1], maxsplit=1)[0] if "# " in body else body
    reasons = " ".join(m.group(1) for m in re.finditer(r"^- [\w-]+:: \[\[[^\]]+\]\] — (.*)$", body, re.M))
    src = re.search(r"^Source: (.*)$", body, re.M)
    rel = re.findall(r"^- ([\w-]+):: \[\[zettel/([^\]|]+)", body, re.M)
    aliases = [str(a) for a in (fm.get("aliases") or [])]
    return {"slug": os.path.basename(path)[:-3], "path": path, "title": title, "aliases": aliases, "tags": tags, "course": course,
            "defn": defn, "reasons": reasons, "source": src.group(1) if src else "", "rel": rel, "text": text}


def load_vault(folder):
    """Chapters (top level, type: chapter) and concept notes (Concepts/*.md, type: concept) of one vault folder."""
    base = os.path.join(ROOT, folder)
    chapters, concepts, mapnote = {}, {}, None
    for f in sorted(os.listdir(base)):
        p = os.path.join(base, f)
        if f.endswith(".md"):
            fm, body = fm_split(open(p, encoding="utf-8").read())
            if fm.get("type") == "chapter":
                chapters[f[:-3]] = {"name": f[:-3], "path": p, "fm": fm, "body": strip_generated(body)}
            if f.endswith("Course Map.md") or f == "09-Foundations.md":
                mapnote = f[:-3]
    cdir = os.path.join(base, "Concepts")
    if os.path.isdir(cdir):
        for f in sorted(os.listdir(cdir)):
            if not f.endswith(".md"):
                continue
            p = os.path.join(cdir, f)
            fm, body = fm_split(open(p, encoding="utf-8").read())
            if fm.get("type") == "concept":
                al = [str(a) for a in (fm.get("aliases") or [])]
                concepts[f[:-3]] = {"name": f[:-3], "path": p, "fm": fm, "aliases": al, "body": strip_generated(body),
                                    "title": str(fm.get("title") or f[:-3])}
    return {"folder": folder, "chapters": chapters, "concepts": concepts, "map": mapnote}


def link_chapter_names(body):
    """Chapter names in the 'Used in:' line of a concept note, in order."""
    m = re.search(r"Used in:\s*(.*)", body)
    return re.findall(r"\[\[([^\]|#]+)", m.group(1)) if m else []


# -------------------------------------------------------------------------------------------------------------- matching
class Matcher:
    def __init__(self, vault):
        self.v = vault
        chs = vault["chapters"]
        self.cvec, self.cseq = {}, {}
        df = collections.Counter()
        for n, c in chs.items():
            heads = " ".join(re.findall(r"^#{1,4} (.*)$", c["body"], re.M))
            al = c["fm"].get("aliases") or []
            al = " ".join(map(str, al)) if isinstance(al, list) else str(al)
            c["vec"] = tf_vector([(c["body"], 1), (heads, 2), (n, 3), (al, 2)])
            c["seq"] = tokens(c["body"], keep_stop=True)
            df.update(c["vec"].keys())
        N = max(len(chs), 1)
        self.idf = {t: math.log((N + 1) / (d + 1)) + 1 for t, d in df.items()}
        self.chapter_links = {n: c["body"] for n, c in chs.items()}

    def concept_candidates(self, z, all_concepts):
        """-> (same [(vault, name)], related [(score, name)])"""
        names = {norm(z["title"])} | {norm(a) for a in z["aliases"]} | {norm(z["slug"].replace("-", " "))}
        names.discard("")
        same = []
        for fold, vlt in all_concepts.items():
            for cn, c in vlt["concepts"].items():
                cnames = {norm(c["title"]), norm(cn)} | {norm(a) for a in c["aliases"]}
                if names & cnames:
                    same.append((fold, cn))
        zv = tf_vector([(z["title"], 3), (" ".join(z["aliases"]), 2), (z["defn"], 1)])
        rel = []
        for cn, c in self.v["concepts"].items():
            if (self.v["folder"], cn) in same:
                continue
            cv = tf_vector([(c["title"], 3), (" ".join(c["aliases"]), 2), (c["body"][:900], 1)])
            s = cosine(zv, cv, {})
            # the concept's own title words must appear in the note's title/aliases/definition: avoids generic overlaps
            ct = set(tokens(c["title"]))
            zt = set(tokens(z["title"] + " " + " ".join(z["aliases"]) + " " + z["defn"]))
            if ct and ct <= zt:
                s += 0.25
            rel.append((s, cn))
        rel.sort(reverse=True)
        return same, rel

    def chapter_scores(self, z, same_in_vault):
        zv = tf_vector([(z["title"], 3), (" ".join(z["aliases"]), 2), (z["defn"], 1), (z["reasons"], 0.5), (z["source"], 1.5)])
        names = [tokens(z["title"], keep_stop=False)] + [tokens(a) for a in z["aliases"]]
        names = [n for n in names if n]
        out = {}
        for n, c in self.v["chapters"].items():
            s = cosine(zv, c["vec"], self.idf)
            ph = 0.0
            for nm in names:
                k = count_phrase([t for t in c["seq"] if t not in STOP], nm)
                if k:
                    ph = max(ph, (1.0 if len(nm) > 1 else 0.5) * math.log1p(k) / 3)
            inh = 0.0
            for cn in same_in_vault:
                used = [u for u in link_chapter_names(self.v["concepts"][cn]["body"]) if u in self.v["chapters"]]
                if n in used:
                    inh = max(inh, 0.6 if used[0] == n else 0.4)
                k = len(re.findall(r"\[\[" + re.escape(cn) + r"[\]|#]", c["body"]))
                if k:
                    inh = max(inh, 0.3 if k < 3 else 0.5)
            out[n] = (s + ph + inh, s, ph, inh)
        return out


def assign_all(zs, vaults):
    plan = {}
    all_concepts = {v["folder"]: v for v in vaults.values()}
    matchers = {f: Matcher(v) for f, v in vaults.items()}
    for z in zs:
        folder, subj = COURSES[z["course"]]
        m = matchers[folder]
        same, rel = m.concept_candidates(z, all_concepts)
        same_here = [cn for f, cn in same if f == folder]
        same_other = []        # cross-vault name matches are coincidences (aliases like "D", "phi"): never linked automatically
        sc = m.chapter_scores(z, same_here)
        ranked = sorted(sc.items(), key=lambda kv: -kv[1][0])
        top = ranked[0] if ranked else None
        plan[z["slug"]] = {"z": z, "vault": folder, "subject": subj, "same": same_here, "same_other": same_other,
                           "related": [(round(s, 2), n) for s, n in rel[:3] if s >= 0.18],
                           "ranked": [(n, round(v[0], 2)) for n, v in ranked[:3]],
                           "chapter": top[0] if top else None, "score": round(top[1][0], 2) if top else 0.0,
                           "margin": round(top[1][0] - ranked[1][1][0], 2) if len(ranked) > 1 else 9}
    return plan


def apply_overrides(plan):
    for slug, o in OVERRIDES.items():
        p = plan.get(slug)
        if not p:
            continue
        if "chapter" in o:
            p["chapter"] = o["chapter"]
            p["pinned"] = True
        if "concepts" in o:
            p["same"] = list(o["concepts"])
        if "related" in o:
            p["related"] = [(1.0, n) for n in o["related"]]


# ----------------------------------------------------------------------------------------------------------------- report
def report(plan, vaults, only=None):
    by = collections.defaultdict(list)
    for slug, p in plan.items():
        by[p["vault"]].append((slug, p))
    for folder, items in by.items():
        if only and only not in folder:
            continue
        print(f"\n===== {folder}  ({len(items)} notes)")
        for slug, p in sorted(items, key=lambda x: (x[1]["chapter"] or "~", x[0])):
            ch = (p["chapter"] or "-")[:34]
            flag = "" if p.get("pinned") or p["margin"] >= 0.08 else " ?"
            sa = ",".join(p["same"]) or ""
            so = ",".join(f"{f[:2]}:{n}" for f, n in p["same_other"])
            rl = ",".join(n for _, n in p["related"])
            alt = p["ranked"][1][0][:12] if len(p["ranked"]) > 1 else ""
            print(f"{slug[:46]:46} | {ch:34} {p['score']:.2f}/{p['margin']:.2f}{flag} alt:{alt:12} | ={sa} {('x:' + so) if so else ''} ~{rl}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--only", help="report only vaults whose folder contains this text")
    a = ap.parse_args()
    zs = [load_zettel(os.path.join(ZDIR, f)) for f in sorted(os.listdir(ZDIR)) if f.endswith(".md")]
    zs = [z for z in zs if z["course"]]
    vaults = {f: load_vault(f) for f, _ in set(COURSES.values())}
    plan = assign_all(zs, vaults)
    apply_overrides(plan)
    report(plan, vaults, a.only)


if __name__ == "__main__":
    main()
