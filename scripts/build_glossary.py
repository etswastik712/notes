"""Generate 00-Home/Glossary.md from all concept notes (frontmatter type: concept).

    .venv/bin/python scripts/build_glossary.py
For each concept: link, subject, scope badges, and its one-line definition (the first `> [!key]` callout, trimmed),
plus which chapters mention it (static back-links).  Re-run after adding or editing concept notes.
"""
import os
import re

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DIRS = [d for d in sorted(os.listdir(ROOT)) if re.match(r"^\d\d-", d)]
SCOPE_ICON = {"taught": "🟢", "extra-book": "🟡", "extra-beyond": "🔵"}


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}, text
    try:
        return yaml.safe_load(m.group(1)) or {}, text[m.end():]
    except Exception:
        return {}, text[m.end():]


def definition(body):
    m = re.search(r"> \[!key\][^\n]*\n((?:>[^\n]*\n?)+)", body)
    if not m:
        return ""
    t = " ".join(l.lstrip("> ").strip() for l in m.group(1).split("\n") if l.strip(">").strip())
    t = re.sub(r"\$\$.*?\$\$", "", t)                # drop display math
    t = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", t)   # [[a|b]] -> b (a cut-off link would break)
    t = re.sub(r"\[\[([^\]]+)\]\]", r"\1", t)
    t = re.sub(r"\s+", " ", t).strip()
    return (t[:230] + "…") if len(t) > 230 else t


concepts, chapters = {}, {}
relpaths = {}
# a concept whose file name is shared with another note (e.g. the other tool's zettel/variance.md) must be linked by path,
# otherwise Obsidian may resolve the bare name to the wrong note
import collections as _c
_names = _c.Counter()
for _dp, _dn, _fs in os.walk(ROOT):
    _dn[:] = [x for x in _dn if x not in (".git", ".obsidian", ".venv", "node_modules", "attachments", "Assets")]
    for _f in _fs:
        if _f.endswith(".md"):
            _names[_f[:-3].lower()] += 1
for d in DIRS:
    # concept notes may sit in a subfolder (e.g. 01-Climate/Concepts/), so walk the tree
    files = sorted((os.path.join(dp, f) for dp, _, fs in os.walk(os.path.join(ROOT, d)) for f in fs),
                   key=lambda x: os.path.basename(x))
    for p in files:
        f = os.path.basename(p)
        if not f.endswith(".md"):
            continue
        fm, body = frontmatter(open(p, encoding="utf-8").read())
        name = f[:-3]
        if fm.get("type") == "concept":
            concepts[name] = (fm, definition(body), body)
            relpaths[name] = os.path.relpath(p, ROOT)[:-3]
        elif fm.get("type") == "chapter":
            chapters[name] = body

rows = []
for name in sorted(concepts, key=str.lower):
    fm, d, _ = concepts[name]
    scope = " ".join(SCOPE_ICON.get(s, "") for s in (fm.get("scope") or []))
    used = [c.split(" ")[0] for c, b in sorted(chapters.items()) if f"[[{name}" in b]
    used_s = " · ".join(f"[[{c}\\|{c.split(' ')[0]}]]" for c in sorted(chapters) if f"[[{name}" in chapters[c])
    d = d.replace("|", "\\|")
    link = f"[[{name}]]" if _names[name.lower()] == 1 else f"[[{relpaths[name]}\\|{name}]]"
    rows.append(f"| {link} | {fm.get('subject','')} | {scope} | {d} | {used_s} |")

out = ["---", "title: Glossary", "tags: [meta, type/meta]", "---", "# Glossary",
       "", f"{len(rows)} concept notes, generated by `scripts/build_glossary.py` (re-run after adding concepts). "
       "🟢 taught · 🟡 extra (book) · 🔵 extra (beyond). The last column lists the chapters that cite the concept.",
       "", "| Concept | Subject | Scope | Definition | Used in |", "|---|---|---|---|---|"] + rows + [""]
path = os.path.join(ROOT, "00-Home", "Glossary.md")
open(path, "w", encoding="utf-8").write("\n".join(out))
print("wrote", os.path.relpath(path, ROOT), len(rows), "concepts")
