def md5(p: Path) -> str:
    h = hashlib.md5()
    with p.open("rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def vault_sizes(topic: str) -> dict[int, list[Path]]:
    d: dict[int, list[Path]] = {}
    for p in (ROOT / topic).rglob("*"):
        if p.is_file():
            d.setdefault(p.stat().st_size, []).append(p)
    return d


def human(n: int) -> str:
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.0f} {u}"
        n /= 1024
    return f"{n:.1f} TB"


def main():
    if not (DRIVE / AR).is_dir():
        raise SystemExit(f"{DRIVE} is not mounted")
    files = sorted(str(p.relative_to(DRIVE)) for p in (DRIVE / AR).rglob("*")
                   if p.is_file() and not SKIP.search(p.name))
    by_topic: dict[str, list[tuple[str, str]]] = {}
    for rel in files:
        done = set()
        for pat, topic, note in RULES:
            if topic not in done and fnmatch.fnmatch(rel, pat):
                by_topic.setdefault(topic, []).append((rel, note))
                done.add(topic)
    for topic, items in sorted(by_topic.items()):
        sizes = vault_sizes(topic)
        rows = []
        for rel, note in items:
            p = DRIVE / rel
            sz = p.stat().st_size
            twin = next((q for q in sizes.get(sz, []) if md5(q) == md5(p)), None)
            invault = f"yes: `{twin.relative_to(ROOT / topic)}`" if twin else "no"
            url = "file://" + quote(str(p))
            name = p.name.replace("|", "-").replace("[", "(").replace("]", ")")
            folder = str(Path(rel).parent.relative_to(AR))
            rows.append(f"| [{name}](<{url}>) | {folder} | {human(sz)} | {note} | {invault} |")
        cmap = TOPIC_MAP.get(topic)
        body = [
            "---", "tags: [sources, shared-drive]", f"topic: {topic}", "---", GEN,
            f"# Shared-drive resources: {topic}", "",
            f"Related files on the shared drive **`{DRIVE}`** (read-only: nothing here was moved or copied). "
            "Links open the file when the drive is mounted (Obsidian: click; or open the path in a file manager). "
            "*In vault* = an identical copy (md5) already sits in this topic folder.", "",
            *( [f"Vault: [[{cmap}]]", ""] if cmap else [] ),
            f"Folder: [{DRIVE}/{AR}](<file://{quote(str(DRIVE / AR))}>)", "",
            "| File | Folder on drive | Size | What it is / where it fits | In vault |", "|---|---|---|---|---|",
            *rows, "",
        ]
        (ROOT / topic).mkdir(parents=True, exist_ok=True)
        (ROOT / topic / OUT).write_text("\n".join(body))
        print(f"{topic}: {len(rows)} files")
        if cmap:
            mp = ROOT / (cmap + ".md")
            line = f"> [!info] Shared drive: related books, past papers and old decks on the shared drive are listed in [[{topic}/shared-drive-sources|shared-drive sources ({len(rows)} files)]]."
            txt = mp.read_text()
            if "/shared-drive-sources|" in txt:
                txt = re.sub(r"> \[!info\] Shared drive:.*", line, txt)
            else:  # put it right after the front matter + title block: before the first '## ' heading
                i = txt.find("\n## ")
                txt = txt[:i] + "\n\n" + line + "\n" + txt[i:] if i > 0 else txt + "\n\n" + line + "\n"
            mp.write_text(txt)


if __name__ == "__main__":
    main()
