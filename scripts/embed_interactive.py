"""Embed the interactive tools into the vault notes and regenerate the hub note.
   For every tool in scripts/interactive/catalog.json, each chapter named in its META "chapters" list gets an
   [!interactive] callout (preview image + links + what to try) between <!-- interactive:start --> / <!-- interactive:end --> markers
   (idempotent: re-running replaces the block). Also writes 00-Home/Interactive Tools.md (hub + coverage).
   .venv/bin/python -W ignore scripts/embed_interactive.py [--dry]
"""
import json, os, re, glob, sys, collections
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
CAT=os.path.join(HERE,"interactive","catalog.json")
START="<!-- interactive:start (generated by scripts/embed_interactive.py; edit the tool in scripts/interactive/tools/, not this block) -->"; END="<!-- interactive:end -->"
ANCHORS=[r"Map of this chapter",r"Summary",r"Practice",r"Check yourself",r"Problems",r"Questions",r"Provenance"]
VAULTS={"CM":("15-Classical-Mechanics","Classical Mechanics"),"ED":("16-Electrodynamics","Electrodynamics"),"QM":("06-Quantum-Mechanics","Quantum Mechanics"),
 "Waves":("07-Waves","Waves"),"TH":("03-Thermodynamics-and-Statistical-Mechanics","Thermodynamics"),"SM":("03-Thermodynamics-and-Statistical-Mechanics","Statistical Mechanics"),
 "CL":("01-Climate","Climate"),"EE":("02-Eco-Evo","Ecology and Evolution"),"LS":("05-Landscapes-Geomorphology","Landscapes and Geomorphology"),
 "NS":("13-Neuroscience","Neuroscience"),"PR":("08-Probability","Probability"),"GT":("10-Group-Theory","Group Theory"),"PA":("11-Proofs-Analysis-Topology","Proofs, Analysis and Topology"),
 "CH":("12-Inorganic-Chemistry","Inorganic Chemistry"),"DM":("14-Differential-Geometry","Differential Geometry")}
ORDER=["CM","ED","QM","Waves","TH","SM","CL","EE","LS","NS","PR","GT","PA","CH","DM"]
def find(name):
    h=glob.glob(os.path.join(ROOT,"*",name+".md"))+glob.glob(os.path.join(ROOT,"*","*",name+".md"))
    return h[0] if h else None
def first_sentence(d):
    m=re.match(r"(.+?[.!?])(\s|$)",d.strip()); return m.group(1) if m else d
def block(tools):
    out=[START]
    for t in tools:
        rel="../Assets/interactive/%s.html"%t["id"]; ab="file://"+os.path.join(ROOT,"Assets","interactive",t["id"]+".html")
        out.append(f"> [!interactive]+ Interactive: {t['title']}\n> {first_sentence(t['desc'])}\n>\n> ![[{t['id']}.png|720]]\n>\n> **Try:** {t['tryit']}\n>\n> [▶ Open the tool in your browser]({rel}) · [absolute link]({ab}) · all tools and coverage: [[Interactive Tools]]\n")
    out.append(END); return "\n".join(out)+"\n"
def insert(path,blk,dry):
    s=open(path).read()
    if START in s and END in s:
        a=s.index(START); b=s.index(END)+len(END)
        new=s[:a]+blk.rstrip("\n")+s[b:]; where="replaced"
    else:
        lines=s.split("\n"); idx=None
        for pat in ANCHORS:
            for i,l in enumerate(lines):
                if re.match(r"^## (\d+\.\s*)?"+pat,l): idx=i; break
            if idx is not None: break
        if idx is None:
            m=s.find("<!-- graph-spine:start")
            if m>=0: new=s[:m].rstrip("\n")+"\n\n## Interactive tools\n\n"+blk+"\n"+s[m:]; where="before atlas"
            else: new=s.rstrip("\n")+"\n\n## Interactive tools\n\n"+blk; where="end"
        else:
            new="\n".join(lines[:idx])+"\n"+blk+"\n"+"\n".join(lines[idx:]); where="before: "+lines[idx][:40]
    if not dry and new!=s: open(path,"w").write(new)
    return where
def chapters_of(vault):
    folder=VAULTS[vault][0]; res=[]
    for f in sorted(os.listdir(os.path.join(ROOT,folder))):
        if f.endswith(".md") and re.match(r"^[A-Z]{2}\d{2} ",f): res.append(f[:-3])
    return res
def main():
    dry="--dry" in sys.argv; cat=json.load(open(CAT)); per=collections.defaultdict(list)
    for t in cat:
        for ch in t["chapters"]: per[ch].append(t)
    for ch,ts in sorted(per.items()):
        p=find(ch)
        if not p: print("MISSING NOTE",ch); continue
        w=insert(p,block(ts),dry); print(f"{ch}: {len(ts)} tool(s) -> {w}")
    hub(cat,per,dry)
def hub(cat,per,dry):
    by=collections.defaultdict(list)
    for t in cat: by[t["vault"]].append(t)
    L=["---","title: Interactive Tools","aliases: [Interactive tools, Visual tools, Intuition tools, Interactive visualisations]","type: hub","status: draft",
       "tags: [type/hub, tool/interactive, status/draft]","---","# Interactive Tools","",
       f"> [!abstract] {len(cat)} self-contained interactive visualisations across {len(by)} subject groups",
       "> Each tool is one HTML file in `Assets/interactive/` (no internet, no install): sliders, live plots, animations and step-through explorers built to give a *picture* of the idea. Open in a browser; every chapter that uses a tool shows its preview image and a link in an *Interactive* callout.","",
       "> [!tip] How to open them",
       "> **In Obsidian** the preview image shows inline; click **▶ Open the tool in your browser** (relative link) or the absolute `file://` link. If Obsidian does not open the link, turn on *Settings → Files and links → Detect all file extensions* (then `Assets/interactive/*.html` become openable), or open the file from the file manager / `xdg-open Assets/interactive/<id>.html`.","> **Rebuild:** `.venv/bin/python -W ignore scripts/build_interactive.py` (builds + checks + previews), then `.venv/bin/python -W ignore scripts/embed_interactive.py` (refreshes the callouts and this note).","",
       "> [!warning] What the tools are and are not",
       "> The tools are my constructions (🔵 extra · beyond): they illustrate and cross-check the chapter content, and every number printed in a *Try it* line was recomputed (chapter scripts or an independent integration) when the tool was built, but a tool is not a source. Where a tool states a textbook value it is the chapter's value; where it uses a simplification (e.g. a constant Shields number, the 2D Maxwell–Boltzmann gas, valence-only MO diagrams) the note under the tool says so.","",
       "## All tools by subject",""]
    for v in ORDER:
        if v not in by: continue
        folder,name=VAULTS[v]; L+= [f"### {name} ({len(by[v])})","","| Tool | What it shows | Chapters |","|---|---|---|"]
        for t in by[v]:
            chs=" · ".join(f"[[{c}]]" for c in t["chapters"])
            L.append(f"| **{t['title']}**<br>[open `{t['id']}`](../Assets/interactive/{t['id']}.html) | {first_sentence(t['desc'])} *Try:* {t['tryit']} | {chs} |")
        L.append("")
    L+=["## Coverage: which chapters have a tool","","A chapter counts as covered if at least one tool is embedded in it. ✓ = at least one tool; the empty cells are the honest to-do list (some chapters are descriptive or reference-style and have nothing natural to animate).","","| Vault | Chapters with a tool | Chapters without a tool yet |","|---|---|---|"]
    covered=set(per.keys())
    for v in ORDER:
        if v in("SM",): continue
        folder,name=VAULTS[v]
        chs=chapters_of(v)
        if v=="TH": chs=[c for c in chs if c[:2] in ("TH","SM")]
        if not chs: L.append(f"| {name} | (course map only) | no chapters written yet |"); continue
        have=[c for c in chs if c in covered]; miss=[c for c in chs if c not in covered]
        nm=name if v!="TH" else "Thermodynamics and Statistical Mechanics"
        L.append(f"| {nm} | {len(have)}/{len(chs)}: "+(", ".join(c.split(" ")[0] for c in have) or "none")+" | "+(", ".join(c.split(" ")[0] for c in miss) or "none")+" |")
    L+=["","Chapters not yet written (Classical Mechanics CM07–CM11, CMX1–CMX2; Electrodynamics ED01–ED02, ED09–ED11, EDX1–EDX2) get their tool when the chapter is written.","","## Conventions for new tools","","- One file per tool in `scripts/interactive/tools/<id>.js`; first line `//META {title, desc, vault, chapters, tryit}`; shared library `lib.js` and `base.css`.","- Match the chapter's verified numbers (default slider values reproduce the worked example) and say so in the note under the tool.","- Give every tool a *Try it* line; keep controls few and labelled; dark/light themes follow the system.","- Rebuild and embed with the two commands above; the hub and callouts regenerate.","","## See also","","[[Home]] · [[Toolkit]] · [[Conventions]] · [[PROGRESS]]",""]
    p=os.path.join(ROOT,"00-Home","Interactive Tools.md")
    if not dry: open(p,"w").write("\n".join(L))
    print("hub written" if not dry else "hub (dry)")
if __name__=="__main__": main()
